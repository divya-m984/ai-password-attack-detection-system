def test_a_run_report_stays_fully_populated(tmp_path: Path) -> None:
    """The live-run report keeps integer counts, including measured zeros."""
    from password_attack_detector.detection.quality import (
        UNAVAILABLE_WHEN_RECONSTRUCTED,
    )

    features = tmp_path / "feature_snapshots.parquet"
    write_snapshots(features)
    output = tmp_path / "detection"
    assert (
        invoke(
            "detection",
            "run",
            "--features",
            str(features),
            "--output-dir",
            str(output),
        ).exit_code
        == 0
    )

    payload = json.loads((output / QUALITY_JSON_FILE).read_text())
    assert payload["report_source"] == "live_run"
    assert payload["unavailable_metrics"] == []
    assert payload["reconstruction_note"] is None
    for name in UNAVAILABLE_WHEN_RECONSTRUCTED:
        assert isinstance(payload[name], int), name
    assert payload["suppressed_total"] == 0
