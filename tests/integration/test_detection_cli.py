def declared_options(command: str) -> set[str]:
    """Return the option flags a subcommand actually declares.

    Read from the click command rather than from rendered help text: the help
    for ``run`` explains in prose that it has no ``--labels`` option, and a
    substring scan would flag that sentence as the very thing it denies.
    """
    import typer.main

    # The objects below are click internals reached through Typer. click ships
    # no type stubs in this environment, so they are annotated Any rather than
    # imported for a type that mypy cannot resolve.
    click_app: Any = typer.main.get_command(app)
    group: Any = click_app.commands["detection"]
    target: Any = group.commands[command]
    flags: set[str] = set()
    for parameter in target.params:
        flags.update(getattr(parameter, "opts", ()))
    return flags


def test_run_declares_no_labels_or_splits_option() -> None:
    """The absence is the enforcement: ground truth cannot reach the engine."""
    flags = declared_options("run")
    assert "--labels" not in flags
    assert "--splits" not in flags
    assert not any("campaign" in flag for flag in flags)


def test_evaluate_is_the_only_command_declaring_labels() -> None:
    for command in ("run", "validate", "profile", "verify-manifest", "catalog"):
        assert "--labels" not in declared_options(command), command
        assert "--splits" not in declared_options(command), command
    assert "--labels" in declared_options("evaluate")
    assert "--splits" in declared_options("evaluate")


def test_only_run_and_validate_declare_an_entity_scope() -> None:
    """Scope reaches alert construction and its validator, and nothing else."""
    for command in ("profile", "evaluate", "catalog", "verify-manifest"):
        assert "--entity-scope" not in declared_options(command), command
    assert "--entity-scope" in declared_options("run")
    assert "--entity-scope" in declared_options("validate")


