def write_marginal_snapshots(path: Path) -> list[str]:
    """Write snapshots that fire one rule at exactly its thresholds.

    Every saturating component contributes zero at exact equality, so the
    signal strength is the configured floor and the resulting risk lands in
    the LOW band -- the smallest finding the pipeline can produce.
    """
    import pyarrow as pa
    import pyarrow.parquet as pq

    catalog = factories.feature_catalog()
    anchors = [_ANCHOR_TEMPLATE.format(index) for index in range(4)]
    rows = [
        factories.bot_row(
            catalog,
            anchor_event_id=anchor,
            anchor_event_time=factories.WHEN + timedelta(hours=index * 4),
            source_attempt_count__15m=20,
            source_interarrival_coefficient_of_variation__15m=0.15,
            source_mean_interarrival_seconds__15m=120.0,
            source_unique_user_agent_count__1h=2,
        )
        for index, anchor in enumerate(anchors)
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(pa.Table.from_pylist(rows), path)
    return anchors


def test_a_low_alert_is_emitted_when_the_floors_permit_it(tmp_path: Path) -> None:
    """LOW is an ordinary alert severity, reachable end to end."""
    import yaml

    from password_attack_detector.detection.serialization import read_alerts

