"""Integration tests for the ``detection`` CLI group.

Fixtures are deliberately tiny and written directly, rather than generated by
running the Phase 2 and Phase 3 pipelines: a CLI test should fail because the
CLI is wrong, not because a generator upstream changed its output. Every test
writes into ``tmp_path`` and nothing runs at development scale.

Two properties are swept continuously. **No command may print an identifier**
-- not an anchor, a detection or alert identifier, an entity-scope pseudonym,
or an absolute path -- and **ground truth may reach only ``evaluate``**, which
is enforced by the absence of a ``--labels`` option everywhere else.
"""

