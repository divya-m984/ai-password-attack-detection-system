from tests.unit.detection import factories

runner = CliRunner()

_PSEUDONYM_RE = re.compile(r"\b(?:u|s|d|sess):[0-9a-f]{32}\b")
_UUID_RE = re.compile(
    r"\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b"
)

#: The four scenario builders the snapshot fixture rotates through.
_BUILDERS = (
    factories.brute_force_row,
    factories.spraying_row,
    factories.stuffing_row,
    factories.quiet_row,
)

#: Anchors are UUID-shaped on purpose: a summary that leaked one would be
#: caught by the identifier sweep rather than passing unnoticed.
_ANCHOR_TEMPLATE = "3f2504e0-4f89-41d3-9a0c-0305e82c33{:02d}"


def invoke(*args: str) -> Result:
    """Run the CLI and return its result."""
    return runner.invoke(app, list(args))


def write_snapshots(
    path: Path, *, count: int = 12, overrides: dict[str, Any] | None = None
) -> list[str]:
    """Write a tiny feature-snapshot table and return its anchors."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    catalog = factories.feature_catalog()
    anchors = [_ANCHOR_TEMPLATE.format(index) for index in range(count)]
    rows = [
        {
            **_BUILDERS[index % len(_BUILDERS)](
                catalog,
                anchor_event_id=anchors[index],
                anchor_event_time=factories.WHEN + timedelta(minutes=index * 3),
            ),
            **(overrides or {}),
        }
        for index in range(count)
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(pa.Table.from_pylist(rows), path)
    return anchors


def write_feature_manifest(path: Path, *, schema_version: str = "1.0.0") -> None:
    """Write a minimal source feature manifest."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(
            {
                "feature_schema_version": schema_version,
                "content_fingerprint": "a" * 64,
            }
        ),
        encoding="utf-8",
    )


def write_ground_truth(
    labels_path: Path, splits_path: Path, anchors: list[str]
) -> None:
    """Write Phase 3-shaped label and split tables for the fixture anchors."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    scenarios = ("brute_force", "password_spraying", "credential_stuffing", "normal")
    splits = ("train", "validation", "test", "novel_anomaly_holdout")
    labels_path.parent.mkdir(parents=True, exist_ok=True)
    pq.write_table(
        pa.Table.from_pylist(
            [
                {
                    "event_id": anchor,
                    "attack_class": scenarios[index % 4],
                    "malicious": index % 4 != 3,
                    "supervised_training_eligible": index % 4 != 3,
                }
                for index, anchor in enumerate(anchors)
            ]
        ),
        labels_path,
    )
    pq.write_table(
        pa.Table.from_pylist(
            [
                {
                    "event_id": anchor,
                    "split": splits[index % 4],
                    "exclusion_reason": None,
                }
                for index, anchor in enumerate(anchors)
            ]
        ),
        splits_path,
    )


def write_campaigns(path: Path, anchors: list[str]) -> None:
    """Write a Phase 2-shaped campaign table."""
    import pyarrow as pa
    import pyarrow.parquet as pq

    pq.write_table(
        pa.Table.from_pylist(
            [
                {"event_id": anchor, "campaign_id": f"campaign-{index % 3:04d}"}
                for index, anchor in enumerate(anchors)
                if index % 4 != 3
            ]
        ),
        path,
    )


def build_artifacts(directory: Path, *, scope: bool = False) -> dict[str, Any]:
    """Produce a published-shaped artifact set directly, bypassing the CLI."""
    catalog = factories.feature_catalog()
    config = DetectionConfig()
    engine = DetectionEngine(config, feature_catalog=catalog)
    anchors = [_ANCHOR_TEMPLATE.format(index) for index in range(12)]
    rows = [
        _BUILDERS[index % len(_BUILDERS)](
            catalog,
            anchor_event_id=anchors[index],
            anchor_event_time=factories.WHEN + timedelta(minutes=index * 3),
        )
        for index in range(12)
    ]
    detections = list(engine.run(rows).fired_detections)
    scored = RiskScorer(config).score(engine.run_diagnostic(rows))
    table = None
    if scope:
        from password_attack_detector.detection.alerts import build_entity_scope_table

        table = build_entity_scope_table(
            [
                EntityScopeRecord(
                    anchor_event_id=anchor,
                    user_scope=f"u:{index:032x}",
                    source_scope=f"s:{index % 2:032x}",
                )
                for index, anchor in enumerate(anchors)
            ]
        )
    alerting = AlertBuilder(config).build(
        scored.assessments, detections=detections, entity_scope=table
    )

    directory.mkdir(parents=True, exist_ok=True)
    write_fired_detections(detections, directory / DETECTIONS_FILE)
    write_risk_assessments(list(scored.assessments), directory / RISK_FILE)
    write_alerts(list(alerting.alerts), directory / ALERTS_FILE)
    return {
        "anchors": anchors,
        "detections": detections,
        "assessments": list(scored.assessments),
        "alerts": list(alerting.alerts),
    }


def assert_sanitized(result: Result, *secrets: str) -> None:
    """Assert no identifier, pseudonym, or absolute path reached the output."""
    output = result.output
    assert not _UUID_RE.search(output), output
    assert not _PSEUDONYM_RE.search(output), output
    assert "/home/" not in output
    for secret in secrets:
        assert secret not in output


